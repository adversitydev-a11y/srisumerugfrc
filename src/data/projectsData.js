export function getProjectData(slug) {
  if (!slug) return projectsData["secretariat-office"] || projectsData["basava-hall"];
  const normalized = slug.toLowerCase().trim().replace(/_/g, "-");
  if (normalized.includes("secretariat")) {
    return projectsData["secretariat-office"];
  }
  if (normalized.includes("basava") || normalized.includes("hall")) {
    return projectsData["basava-hall"];
  }
  if (normalized.includes("kaivalya")) {
    return projectsData["kaivalya"];
  }
  if (normalized.includes("harivishram")) {
    return projectsData["harivishram"];
  }
  if (normalized.includes("bougainville") || normalized.includes("parva")) {
    return projectsData["bougainville"];
  }
  if (normalized.includes("jst") || normalized.includes("param")) {
    return projectsData["jst-param"];
  }
  if (normalized.includes("purva") || normalized.includes("aerocity")) {
    return projectsData["purva-aerocity"];
  }
  if (normalized.includes("dhyan") || normalized.includes("mandir")) {
    return projectsData["dhyan-mandir"];
  }
  if (normalized.includes("shankara")) {
    return projectsData["shankara"];
  }
  return projectsData[normalized] || null;
}

export function getAllProjects() {
  return Object.values(projectsData);
}

