export const blogPostSlugs = Object.keys(blogData);

export function getBlogPostData(slug) {
  if (!slug) return blogData[blogPostSlugs[0]];
  const cleanSlug = slug.toLowerCase().trim();
  return blogData[cleanSlug] || null;
}

export function getAllBlogPosts() {
  return blogPostSlugs.map((slug) => blogData[slug]);
}

export function getOtherBlogPosts(currentSlug, count = 3) {
  return blogPostSlugs.filter((slug) => slug !== currentSlug).slice(0, count).map((slug) => blogData[slug]);
}
